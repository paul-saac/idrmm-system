import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { runInNewContext } from 'node:vm';
import ts from 'typescript';
const require=createRequire(import.meta.url);
const {PGlite}=require('@electric-sql/pglite');
const exports={};
runInNewContext(ts.transpileModule(readFileSync(new URL('./quantity-limit.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports});
test('remaining quantity excludes today from prior work and handles completion, zero plans and decimal quantities',()=>{
 assert.equal(exports.remainingQuantity(250,100,25),175);
 assert.equal(exports.remainingQuantity(250,100,0),150);
 assert.equal(exports.remainingQuantity(60,0,0),60);
 assert.equal(exports.remainingQuantity(0,0,0),0);
 assert.equal(exports.remainingQuantity(60,70,0),0);
 assert.equal(exports.remainingQuantity(0.3,0.2,0),0.1);
 assert.equal(exports.exceedsQuantity(175,175),false);
 assert.equal(exports.exceedsQuantity(175.01,175),true);
});
async function fixture(){
 const db=new PGlite();
 await db.exec(`create role anon;
 create function system_backup_maintenance() returns boolean language sql as $$select false$$;
 create table estimate_tasks(id bigint primary key,estimated_quantity numeric);
 create table estimate_categories(id bigint primary key,estimated_quantity numeric);
 insert into estimate_tasks values(1,60);insert into estimate_categories values(1,250);
 create table task_progress_entries(id bigint generated by default as identity primary key,task_id bigint references estimate_tasks(id),entry_date date not null,quantity_completed numeric not null,unique(task_id,entry_date));
 create table category_progress_entries(id bigint generated by default as identity primary key,category_id bigint references estimate_categories(id),entry_date date not null,quantity_completed numeric not null,unique(category_id,entry_date));`);
 await db.exec(readFileSync(new URL('../../supabase/migrations/0122_progress_quantity_limits.sql',import.meta.url),'utf8'));
 return db;
}
for(const kind of ['task','category'])test(`database ${kind} quantity cap rejects excess and handles daily replacements and decimal totals`,async()=>{
 const db=await fixture();try{
 const table=kind+'_progress_entries',parent=kind==='task'?'estimate_tasks':'estimate_categories';
 await db.exec(`update ${parent} set estimated_quantity=60; insert into ${table}(${kind}_id,entry_date,quantity_completed) values(1,'2026-11-01',40)`);
 await assert.rejects(db.exec(`insert into ${table}(${kind}_id,entry_date,quantity_completed) values(1,'2026-11-02',21)`),/remaining planned quantity/);
 await db.exec(`insert into ${table}(${kind}_id,entry_date,quantity_completed) values(1,'2026-11-02',20) on conflict(${kind}_id,entry_date) do update set quantity_completed=excluded.quantity_completed`);
 await db.exec(`insert into ${table}(${kind}_id,entry_date,quantity_completed) values(1,'2026-11-02',15) on conflict(${kind}_id,entry_date) do update set quantity_completed=excluded.quantity_completed`);
 assert.equal(Number((await db.query(`select sum(quantity_completed) total from ${table}`)).rows[0].total),55);
 await assert.rejects(db.exec(`update ${table} set quantity_completed=21 where entry_date='2026-11-02'`),/remaining planned quantity/);
 await assert.rejects(db.exec(`update ${table} set quantity_completed='NaN' where entry_date='2026-11-02'`),/finite/);
 await db.exec(`delete from ${table};update ${parent} set estimated_quantity=0.3;insert into ${table}(${kind}_id,entry_date,quantity_completed) values(1,'2026-11-01',0.1),(1,'2026-11-02',0.2)`);
 await assert.rejects(db.exec(`insert into ${table}(${kind}_id,entry_date,quantity_completed) values(1,'2026-11-03',0.01)`),/remaining planned quantity/);
 }finally{await db.close();}
});
