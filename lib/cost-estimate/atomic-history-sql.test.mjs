import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, sep, basename } from 'node:path';
import { execFileSync } from 'node:child_process';
import { createServer } from 'node:net';
import pg from 'pg';

const bin = process.env.IDRMM_TEST_PG_BIN ?? 'C:\\Program Files\\PostgreSQL\\18\\bin';
const migration = readFileSync(new URL('../../supabase/migrations/0110_atomic_gantt_history.sql', import.meta.url), 'utf8');
test('Gantt history is atomic, bounded, project scoped, preserves actual work, and handles rapid edits', { skip: !existsSync(join(bin,'initdb.exe')), timeout: 60000 }, async t => {
  const temporary = mkdtempSync(join(tmpdir(),'idrmm-gantt-sql-'));
  const data = join(temporary,'data');
  const probe = createServer();
  await new Promise(resolve => probe.listen(0,'127.0.0.1',resolve));
  const port = probe.address().port;
  await new Promise(resolve => probe.close(resolve));
  const run = (exe,args,input) => execFileSync(join(bin,exe),args,{input,encoding:'utf8',windowsHide:true,timeout:15000,
    stdio: exe === 'pg_ctl.exe' ? 'ignore' : ['pipe','pipe','pipe']});
  let started = false;
  try {
    try {
      run('initdb.exe',['-D',data,'-U','postgres','-A','trust','--no-locale','--encoding=UTF8']);
      run('pg_ctl.exe',['-D',data,'-l',join(temporary,'server.log'),'-o',`-h 127.0.0.1 -p ${port} -F`,'-w','-t','10','start']);
      started = true;
    } catch (error) {
      t.diagnostic(error.stderr?.toString().slice(-600) || error.message);
      t.skip('The isolated local PostgreSQL test server could not start. No live database was accessed.'); return;
    }
    const sql = text => run('psql.exe',['-X','-h','127.0.0.1','-p',String(port),'-U','postgres','-d','postgres','-v','ON_ERROR_STOP=1','-qAt'],text).trim();
    sql(`create role anon; create role authenticated;
      create schema auth;
      create function auth.uid() returns uuid language sql as $$select coalesce(nullif(current_setting('test.actor',true),''),'00000000-0000-0000-0000-000000000001')::uuid$$;
      create table projects(id bigint primary key,access text,gantt_undo_cursor_id bigint);
      create table estimate_categories(id bigint generated by default as identity primary key,project_id bigint references projects(id),category_name text not null,planned_start_date date,planned_end_date date,predecessor_category_id bigint references estimate_categories(id) on delete set null,predecessor_task_id bigint);
      create table estimate_tasks(id bigint generated by default as identity primary key,project_id bigint references projects(id),category_id bigint references estimate_categories(id) on delete cascade,task_name text not null,planned_start_date date,planned_end_date date,percent_complete integer not null default 0,predecessor_category_id bigint references estimate_categories(id) on delete set null,predecessor_task_id bigint references estimate_tasks(id) on delete set null,check(planned_end_date>=planned_start_date));
      alter table estimate_categories add foreign key(predecessor_task_id) references estimate_tasks(id) on delete set null;
      create table estimate_task_other_costs(id bigint generated by default as identity primary key,task_id bigint references estimate_tasks(id) on delete cascade,category_id bigint references estimate_categories(id) on delete cascade,amount numeric);
      create table estimate_task_material_assignments(id bigint generated by default as identity primary key,task_id bigint references estimate_tasks(id) on delete cascade,amount numeric);
      create table estimate_category_material_assignments(id bigint generated by default as identity primary key,category_id bigint references estimate_categories(id) on delete cascade,amount numeric);
      create table gantt_snapshots(id bigint generated always as identity primary key,project_id bigint references projects(id),snapshot jsonb,created_by uuid);
      alter table projects add foreign key(gantt_undo_cursor_id) references gantt_snapshots(id) on delete set null;
      create table task_progress_entries(task_id bigint references estimate_tasks(id) on delete cascade,actual numeric);
      create table category_progress_entries(category_id bigint references estimate_categories(id) on delete cascade,actual numeric);
      create table task_worker_assignments(task_id bigint references estimate_tasks(id) on delete cascade);
      create table category_worker_assignments(category_id bigint references estimate_categories(id) on delete cascade);
      create table equipment_task_assignments(task_id bigint references estimate_tasks(id) on delete set null,category_id bigint references estimate_categories(id) on delete set null);
      create table project_safety_incidents(task_id bigint references estimate_tasks(id) on delete set null,category_id bigint references estimate_categories(id) on delete set null);
      create function app_session_is_active() returns boolean language sql as $$select coalesce(current_setting('test.session',true),'active')='active'$$;
      create function invitation_setup_complete() returns boolean language sql as $$select coalesce(current_setting('test.invite',true),'complete')='complete'$$;
      create function project_access_level(project bigint) returns text language sql as $$select access from projects where id=project$$;
      create function system_backup_maintenance() returns boolean language sql as $$select coalesce(current_setting('test.maintenance',true),'false')='true'$$;
      insert into projects(id,access) values(1,'edit'),(2,'edit'),(3,'view');
      insert into estimate_categories(id,project_id,category_name) values(10,1,'Main'),(20,2,'Other');
      insert into estimate_tasks(id,project_id,category_id,task_name,planned_start_date,planned_end_date,percent_complete) values(10,1,10,'One','2026-03-01','2026-03-05',37),(11,1,10,'Two','2026-03-02','2026-03-06',0),(20,2,20,'Other','2026-03-01','2026-03-05',50);
      insert into estimate_task_material_assignments(id,task_id,amount) values(10,10,40);
      insert into task_progress_entries values(10,37);
      grant usage on schema public,auth to authenticated;
      grant select on all tables in schema public to authenticated;
      grant insert,update,delete on estimate_categories,estimate_tasks,estimate_task_other_costs,estimate_task_material_assignments,estimate_category_material_assignments,gantt_snapshots to authenticated;
      grant usage,select on all sequences in schema public to authenticated;
      alter table estimate_categories enable row level security;
      create policy edit_categories on estimate_categories to authenticated using(project_id=1) with check(project_id=1);
      alter table estimate_tasks enable row level security;
      create policy edit_tasks on estimate_tasks to authenticated using(project_id=1) with check(project_id=1);
      create table test_writes(tab text,id bigint);
      grant insert on test_writes to authenticated;
      create function test_count_writes() returns trigger language plpgsql as $$begin insert into test_writes values(TG_TABLE_NAME,new.id);return new;end$$;
      create trigger count_task_writes after update on estimate_tasks for each row execute function test_count_writes();
    `);
    sql(migration); sql(migration);
    const call=(action,project=1,prefix='set role authenticated;')=>sql(`${prefix}select gantt_history(${project},'${action}');`);
    const edit=(statement)=>sql(`set role authenticated;${statement};select gantt_history(1,'checkpoint');`);
    const state=()=>JSON.parse(sql('select gantt_snapshot(1);'));
    call('reset');
    const initial=state();
    // Independent rapid changes produce independent checkpoints, including a rename.
    edit("update estimate_tasks set planned_start_date='2026-03-02',planned_end_date='2026-03-06' where id=10");
    edit("update estimate_tasks set task_name='Renamed' where id=11");
    assert.equal(JSON.parse(call('undo')).canRedo,true); assert.equal(state().tasks.find(x=>x.id===11).task_name,'Two');
    assert.equal(JSON.parse(call('undo')).canUndo,false); assert.deepEqual(state(),initial);
    call('redo'); call('redo'); assert.equal(state().tasks.find(x=>x.id===11).task_name,'Renamed');
    // Only a changed row is updated, never all rows in a large snapshot.
    sql('truncate test_writes'); call('undo');
    assert.equal(sql('select count(*) from test_writes'), '1');
    assert.equal(sql('select percent_complete from estimate_tasks where id=10'),'37');
    assert.equal(sql('select actual from task_progress_entries where task_id=10'),'37');
    // New edits after Undo discard redo; no-op saves add no history entry.
    edit("update estimate_tasks set task_name='Branch' where id=11");
    assert.throws(()=>call('redo'));
    const count=sql('select count(*) from gantt_snapshots');call('checkpoint');assert.equal(sql('select count(*) from gantt_snapshots'),count);
    // One grouped action moves both tasks and one Undo restores both.
    const beforeGroup=state();
    edit("update estimate_tasks set planned_start_date=planned_start_date+3,planned_end_date=planned_end_date+3 where project_id=1");
    call('undo');assert.deepEqual(state(),beforeGroup);call('redo');
    // Dependency references in both directions survive deletion/recreation.
    edit("insert into estimate_categories(id,project_id,category_name) values(12,1,'Milestone');insert into estimate_tasks(id,project_id,category_id,task_name,predecessor_category_id) values(12,1,10,'Inspect',12);update estimate_categories set predecessor_task_id=12 where id=12");
    call('undo');assert.equal(sql('select count(*) from estimate_tasks where id=12'),'0');call('redo');
    assert.equal(sql('select predecessor_task_id from estimate_categories where id=12'),'12');assert.equal(sql('select predecessor_category_id from estimate_tasks where id=12'),'12');
    // A late restore error rolls back earlier rows AND the history cursor.
    edit("update estimate_tasks set task_name='Newest' where id=10");
    const beforeFailure=state(), cursor=sql('select gantt_undo_cursor_id from projects where id=1');
    sql(`create function fail_history_test() returns trigger language plpgsql as $$begin if new.task_name<>'Newest' then raise exception 'Forced late failure';end if;return new;end$$;
      create trigger fail_restore before update on estimate_tasks for each row when(new.id=10) execute function fail_history_test();`);
    assert.throws(()=>call('undo'));assert.deepEqual(state(),beforeFailure);assert.equal(sql('select gantt_undo_cursor_id from projects where id=1'),cursor);
    sql('drop trigger fail_restore on estimate_tasks');
    // Refuse overwriting another editor, an uncheckpointed change, or actual records.
    assert.throws(()=>call('undo',1,"set role authenticated;set test.actor='00000000-0000-0000-0000-000000000002';"));
    assert.throws(()=>call('undo',1,"set role authenticated;set test.session='expired';"));
    assert.throws(()=>call('undo',1,"set role authenticated;set test.invite='pending';"));
    assert.throws(()=>call('undo',1,"set role authenticated;set test.maintenance='true';"));
    assert.throws(()=>call('reset',3));assert.throws(()=>call('undo',1,'set role anon;'));
    sql("update estimate_tasks set task_name='Concurrent edit' where id=11");assert.throws(()=>call('undo'));
    call('reset');edit("update estimate_tasks set task_name='Before overlap' where id=11");
    // Hold a real concurrent edit open: Undo must wait for its row lock, then
    // detect the committed change instead of overwriting it with a stale snapshot.
    const connection={host:'127.0.0.1',port,user:'postgres',database:'postgres'};
    const writer=new pg.Client(connection), reader=new pg.Client(connection);
    await writer.connect();await reader.connect();
    try {
      await writer.query("begin;set role authenticated;update estimate_tasks set task_name='Concurrent edit' where id=11");
      await reader.query('set role authenticated');let settled=false;
      const overlapping=reader.query("select gantt_history(1,'undo')");
      overlapping.then(()=>settled=true,()=>settled=true);
      await new Promise(resolve=>setTimeout(resolve,40));assert.equal(settled,false);
      await writer.query('commit');
      await assert.rejects(overlapping,error=>error.code==='40001');
      assert.equal(state().tasks.find(x=>x.id===11).task_name,'Concurrent edit');
    } finally { await writer.query('rollback');await writer.end();await reader.end(); }
    call('reset');edit("insert into estimate_tasks(id,project_id,category_id,task_name) values(13,1,10,'New')");
    sql('insert into task_progress_entries values(13,10)');assert.throws(()=>call('undo'));assert.equal(sql('select actual from task_progress_entries where task_id=13'),'10');
    // A different author's new checkpoint invalidates the old stack rather than
    // skipping over their work to an unrelated checkpoint owned by this user.
    call('checkpoint',1,"set role authenticated;set test.actor='00000000-0000-0000-0000-000000000002';");
    assert.throws(()=>call('undo'));
    edit("update estimate_tasks set task_name='Own edit after collaborator' where id=11");
    assert.throws(()=>call('undo'));
    sql("update estimate_tasks set task_name='Concurrent edit' where id=11");
    // 100 fast edits and 100 traversals with the real PostgreSQL functions.
    call('reset');
    sql(`set role authenticated;do $$begin for i in 1..100 loop update estimate_tasks set task_name='Edit '||i where id=11;perform gantt_history(1,'checkpoint');end loop;end$$;`);
    assert.equal(sql('select count(*) from gantt_snapshots where project_id=1'),'101');
    sql(`set role authenticated;do $$begin for i in 1..100 loop perform gantt_history(1,'undo');end loop;end$$;`);
    assert.equal(state().tasks.find(x=>x.id===11).task_name,'Concurrent edit');
    sql(`set role authenticated;do $$begin for i in 1..100 loop perform gantt_history(1,'redo');end loop;end$$;`);
    assert.equal(state().tasks.find(x=>x.id===11).task_name,'Edit 100');
    assert.equal(sql('select task_name from estimate_tasks where id=20'),'Other');

  } finally {
    if (started || existsSync(join(data,'postmaster.pid'))) run('pg_ctl.exe',['-D',data,'-m','immediate','-w','stop']);
    const absolute=resolve(temporary), parent=resolve(tmpdir())+sep;
    if (!absolute.startsWith(parent) || !basename(absolute).startsWith('idrmm-gantt-sql-')) throw Error('Refusing to remove an unexpected test directory.');
    rmSync(absolute,{recursive:true,force:true});
  }
});
