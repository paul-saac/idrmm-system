const change=(db,id,expected,status)=>db.query('select set_equipment_service_status($1,$2,$3) result',[id,expected,status]);

test('maintenance atomically closes checkout and task periods, clears plans and preserves history, then releases to Available',{skip:!PGlite},async()=>{
  const db=await database();try {
    assert.deepEqual((await change(db,1,'assigned','maintenance')).rows[0].result.projectIds,[4]);
    assert.equal((await db.query('select status from equipment where id=1')).rows[0].status,'maintenance');
    assert.equal((await db.query('select current_project_id from equipment where id=1')).rows[0].current_project_id,null);
    assert.ok((await db.query('select returned_at from equipment_assignments where id=10')).rows[0].returned_at);
    assert.equal((await db.query('select release_reason from equipment_task_assignments where id=20')).rows[0].release_reason,'returned');
    assert.equal((await db.query('select count(*)::int n from equipment_task_plans')).rows[0].n,0);
    // Simulate leftover allocations from the older maintenance implementation.
    await db.exec("insert into equipment_task_plans values(1,8,'task-20')");
    assert.deepEqual((await change(db,1,'maintenance','available')).rows[0].result.projectIds,[8]);
    assert.equal((await db.query('select count(*)::int n from equipment_task_plans')).rows[0].n,0);
    assert.equal((await db.query('select status from equipment where id=1')).rows[0].status,'available');
    await assert.rejects(change(db,1,'maintenance','available'),/has changed/);
    await change(db,2,'available','maintenance');
    assert.equal((await db.query('select count(*)::int n from equipment_assignments')).rows[0].n,1);
    assert.equal((await db.query("select prosecdef from pg_proc where proname='set_equipment_service_status'")).rows[0].prosecdef,false);
  } finally {await db.close();}
});

test('maintenance rejects unauthorized sessions, pending setup, backup locks and invalid transitions without writes',{skip:!PGlite},async()=>{
  const db=await database();try {
    for(const role of ['foreman','project_manager']) {
      await db.query("select set_config('test.role',$1,false)",[role]);
      await assert.rejects(change(db,1,'assigned','maintenance'),/Only administrators/);
    }
    await db.exec("set test.role='admin'");
    for(const [key,value,message] of [['active','no',/Only administrators/],['setup','no',/Only administrators/],['backup','yes',/temporarily paused/]]) {
      await db.query('select set_config($1,$2,false)',['test.'+key,value]);
      await assert.rejects(change(db,1,'assigned','maintenance'),message);
      await db.query('select set_config($1,$2,false)',['test.'+key,value==='no'?'yes':'no']);
    }
    await assert.rejects(change(db,3,'retired','maintenance'),/valid equipment status/);
    await assert.rejects(change(db,1,'assigned','available'),/valid equipment status/);
    assert.equal((await db.query('select returned_at from equipment_assignments where id=10')).rows[0].returned_at,null);
    assert.equal((await db.query('select status from equipment where id=1')).rows[0].status,'assigned');
  } finally {await db.close();}
});

