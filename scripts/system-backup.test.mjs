const require = createRequire(import.meta.url);
const { PGlite } = require('@electric-sql/pglite');
const migration = await readFile(new URL('../supabase/migrations/0105_system_backup_restore.sql', import.meta.url), 'utf8');
const id = n => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;

async function setup() {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated;
    create schema auth; create schema storage;
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    create table auth.users(id uuid primary key,email text);
    create table auth.sessions(id uuid primary key,user_id uuid references auth.users on delete cascade);
    create table auth.schema_migrations(version text primary key);
    create table public.profiles(id uuid primary key references auth.users,first_name text,last_name text,role text,status text default 'active',invitation_pending boolean default false);
    create table public.projects(id bigint generated by default as identity primary key,name text,status text default 'completed',archived_at timestamptz);
    create table public.logs(id bigint primary key,project_id bigint references projects,amount numeric);
    create table storage.buckets(id text primary key);
    create table storage.objects(id bigint primary key,bucket_id text references storage.buckets,name text);
    insert into auth.users values('${id(1)}','super@example.test'),('${id(2)}','admin@example.test'),('${id(3)}','pm@example.test'),('${id(4)}','foreman@example.test'),('${id(5)}','pending@example.test');
    insert into public.profiles values
      ('${id(1)}','Super','Admin','super_admin','active',false),
      ('${id(2)}','Owner','Admin','admin','active',false),
      ('${id(3)}','Project','Manager','project_manager','active',false),
      ('${id(4)}','Site','Foreman','foreman','active',false),
      ('${id(5)}','Pending','User','super_admin','active',true);
    insert into public.projects(name,archived_at) values('Archived project',now());
    insert into public.logs values(10,1,800);
    insert into storage.buckets values('incident-evidence');
    insert into storage.objects values(1,'incident-evidence','1/photo.jpg');
    grant usage on schema public,auth,storage to authenticated;
    grant select,insert,update,delete on all tables in schema public,storage to authenticated;
    grant usage,select on all sequences in schema public to authenticated;
  `);
  await db.exec(migration);
  return db;
}
async function as(db, actor) {
  await db.exec(`reset role; select set_config('request.jwt.claim.sub','${actor ? id(actor) : ''}',false); ${actor ? 'set role authenticated;' : ''}`);
}
async function ready(db) {
  await as(db, null);
  await db.exec("update public.system_backup_state set worker_ready=true,worker_heartbeat=now()");
}

test('only an accepted active Super Admin can request backups or read history; control tables remain private', async () => {
  const db = await setup();
  try {
    await ready(db);
    for (const actor of [2,3,4,5]) {
      await as(db, actor);
      await assert.rejects(db.exec('select system_backup_status()'), /Only Super/);
      await assert.rejects(db.exec("select system_backup_request('backup')"), /Only Super/);
    }
    await as(db, 1);
    await assert.rejects(db.exec('select recovery_token_hash from system_backup_state'), /permission denied/);
    const status = (await db.query('select system_backup_status() as status')).rows[0].status;
    assert.equal('recovery_token_hash' in status.state, false);
    assert.equal(status.snapshots.length, 0);
    assert.ok((await db.query("select system_backup_request('backup') as id")).rows[0].id);
    await assert.rejects(db.exec("select system_backup_request('backup')"), /already queued/);
  } finally { await db.close(); }
});

test('offline workers and invalid restore targets cannot enqueue work', async () => {
  const db = await setup();
  try {
    await as(db, 1);
    await assert.rejects(db.exec("select system_backup_request('backup')"), /worker is offline/);
    await ready(db); await as(db, 1);
    await assert.rejects(db.exec("select system_backup_request('other')"), /valid backup action/);
    await assert.rejects(db.exec("select system_backup_request('restore','" + id(8) + "')"), /verified backup/);
    await as(db, null);
    await db.exec("update system_backup_state set recovery_required=true,maintenance=true");
    await as(db, 1);
    await assert.rejects(db.exec("select system_backup_request('backup')"), /Recovery is required/);
  } finally { await db.close(); }
});

test('maintenance blocks browser and privileged API writes including attachments; a private recovery lease permits only the worker', async () => {
  const db = await setup();
  try {
    const token = 'c'.repeat(64);
    await db.query("update system_backup_state set maintenance=true,recovery_token_hash=encode(sha256(convert_to($1,'UTF8')),'hex')", [token]);
    await as(db, 1);
    await assert.rejects(db.exec("update projects set name='Denied' where id=1"), /maintenance is active/);
    await assert.rejects(db.exec("delete from logs where id=10"), /maintenance is active/);
    await assert.rejects(db.exec("insert into storage.objects values(2,'incident-evidence','1/new.jpg')"), /maintenance is active/);
    await as(db, null);
    await assert.rejects(db.exec("update profiles set first_name='Denied' where id='" + id(1) + "'"), /maintenance is active/);
    await assert.rejects(db.exec('truncate logs'), /maintenance is active/);
    await db.query("select set_config('request.headers',$1,false)", [JSON.stringify({ 'x-idrmm-recovery-token': 'wrong' })]);
    await assert.rejects(db.exec("delete from storage.objects where id=1"), /maintenance is active/);
    await db.query("select set_config('request.headers',$1,false)", [JSON.stringify({ 'x-idrmm-recovery-token': token })]);
    await db.exec("update storage.objects set name='1/restored.jpg' where id=1");
    assert.equal((await db.query('select name from storage.objects where id=1')).rows[0].name, '1/restored.jpg');
  } finally { await db.close(); }
});

test('restore confirmation is enforced by the database even for direct RPC callers', async () => {
  const db = await setup();
  try {
    await ready(db);
    await db.query(`insert into system_backup_snapshots(id,created_by_name,purpose,size_bytes,artifact_sha256,key_id,schema_fingerprint,table_count,file_count,recovery_admin_ids)
      values($1,'Super Admin','manual',100,'hash','key','schema',2,0,$2)`, [id(8), [id(1)]]);
    await as(db, 1);
    await assert.rejects(db.query("select system_backup_request('restore',$1)", [id(8)]), /confirmation exactly/);
    await assert.rejects(db.query("select system_backup_request('restore',$1,'RESTORE')", [id(8)]), /confirmation exactly/);
    assert.ok((await db.query("select system_backup_request('restore',$1,$2) as id", [id(8), `RESTORE ${id(8).slice(0,8)}`])).rows[0].id);
  } finally { await db.close(); }
});

test('same-schema restore is transactional, preserves recovery controls and sequence state, and verifies relationships', async () => {
  const db = await setup();
  try {
    await db.exec(`create function public.handle_new_user() returns trigger language plpgsql as $$begin insert into public.profiles(id,first_name,role) values(new.id,'Generated','foreman'); return new; end$$;
      create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();`);
    const database = await describeDatabase(db);
    const counts = await countTables(db, database.tables);
    assert.ok(database.tables.every(t => !t.name.startsWith('system_backup_')));
    assert.ok(!database.tables.some(t => t.schema==='auth' && t.name==='schema_migrations'));
    const manifest = { database, counts };
    const verify = await restoreVerificationSql(db, manifest);
    const apply = await restoreApplySql(db, manifest);
    const token = 'd'.repeat(64);
    await db.query("update system_backup_state set maintenance=true,recovery_required=true,recovery_token_hash=encode(sha256(convert_to($1,'UTF8')),'hex')", [token]);
    // Generated recovery SQL is exercised with real PostgreSQL constraints,
    // not a mock of the restore verification logic.
    const stage = async () => {
      for (let i=0;i<database.tables.length;i++) {
        const table=database.tables[i];
        await db.exec(`insert into pg_temp.${quoteId(`idrmm_restore_${i}`)} select * from ${quoteId(table.schema)}.${quoteId(table.name)}`);
      }
    };
    await db.exec('begin;');
    await db.exec(restorePrelude(database.tables, token));
    await stage();
    await db.exec(apply);
    await db.exec("select setval('projects_id_seq',1,true)");
    await db.exec(verify);
    await db.exec('commit;');
    assert.equal(Number((await db.query('select amount from logs where id=10')).rows[0].amount), 800);
    assert.equal((await db.query('select maintenance,recovery_required from system_backup_state')).rows[0].maintenance, true);
    assert.ok((await db.query('select archived_at from projects where id=1')).rows[0].archived_at);
    assert.equal((await db.query('select first_name,role from profiles where id=$1',[id(1)])).rows[0].role,'super_admin');
    assert.equal((await describeDatabase(db)).fingerprint,database.fingerprint);
    await db.exec("begin;");
    await db.exec(restorePrelude(database.tables, token));
    await stage();
    const index=database.tables.findIndex(t=>t.schema==='public' && t.name==='logs');
    await db.exec(`update pg_temp.${quoteId(`idrmm_restore_${index}`)} set project_id=999`);
    await assert.rejects(db.exec(apply), /foreign key/);
    await db.exec('rollback;');
    assert.equal((await db.query('select project_id from logs where id=10')).rows[0].project_id, 1);
    await db.exec("update system_backup_state set maintenance=false,recovery_required=false");
    assert.equal((await db.query("insert into projects(name) values('Next') returning id")).rows[0].id, 2);
  } finally { await db.close(); }
});
