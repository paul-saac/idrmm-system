create or replace function public.assert_estimate_dependency_graph(p_project_id bigint)
returns void language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_cycle boolean;
begin
 with recursive edges(source,dest) as(
   select predecessor_key,successor_key||case when successor_category_id is not null and exists(select 1 from public.estimate_tasks t where t.category_id=d.successor_category_id) then ':start' else '' end
     from public.estimate_dependencies d where project_id=p_project_id
   union select 'category:'||category_id||':start','task:'||id from public.estimate_tasks where project_id=p_project_id
   union select 'task:'||id,'category:'||category_id from public.estimate_tasks where project_id=p_project_id
 ), walk(root,node) as(
   select source,dest from edges union select walk.root,edges.dest from edges join walk on edges.source=walk.node
 ) select exists(select 1 from walk where root=node) into v_cycle;
 if v_cycle then raise exception 'These dependencies would create a circular dependency.' using errcode='22023';end if;
end $$;
create or replace function public.lock_estimate_dependency_edit()
returns trigger language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_project bigint;
begin
 v_project:=case when tg_op='DELETE' then old.project_id else new.project_id end;
 if public.app_session_is_active() is not true or public.invitation_setup_complete() is not true or public.project_access_level(v_project) is distinct from 'edit' then
   raise exception 'Project editing is not permitted.' using errcode='42501';end if;
 if public.system_backup_maintenance() then raise exception 'Saving is temporarily paused.' using errcode='55000';end if;
 if tg_op='UPDATE' and old.project_id<>new.project_id then raise exception 'Dependencies cannot move between projects.' using errcode='22023';end if;
 perform pg_advisory_xact_lock(hashtextextended('idrmm-gantt-project:'||v_project::text,0));
 return case when tg_op='DELETE' then old else new end;
end $$;
create or replace function public.validate_estimate_dependency_edit()
returns trigger language plpgsql security invoker set search_path=public,pg_temp as $$
begin
 perform public.assert_estimate_dependency_graph(case when tg_op='DELETE' then old.project_id else new.project_id end);return null;
end $$;
create constraint trigger dependency_membership_valid after update of category_id on public.estimate_tasks deferrable initially deferred for each row execute function public.validate_estimate_dependency_edit();
create trigger dependency_edit_lock before insert or update or delete on public.estimate_dependencies for each row execute function public.lock_estimate_dependency_edit();
create constraint trigger dependency_graph_valid after insert or update or delete on public.estimate_dependencies deferrable initially deferred for each row execute function public.validate_estimate_dependency_edit();

-- Older forms own only their one single-column link. Preserve all other links.
create or replace function public.bridge_estimate_predecessor()
returns trigger language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_target text;v_old text;
begin
 if current_setting('idrmm.dependency_sync',true)='edges' then return new;end if;
 v_target:=case when tg_table_name='estimate_tasks' then 'task:' else 'category:' end||new.id;
 if tg_op='UPDATE' then
   if (old.predecessor_category_id,old.predecessor_task_id) is not distinct from (new.predecessor_category_id,new.predecessor_task_id) then return new;end if;
   v_old:=coalesce('category:'||old.predecessor_category_id,'task:'||old.predecessor_task_id);
   delete from public.estimate_dependencies where project_id=new.project_id and successor_key=v_target and predecessor_key=v_old;
 end if;
 if num_nonnulls(new.predecessor_category_id,new.predecessor_task_id)=1 then
   insert into public.estimate_dependencies(project_id,predecessor_category_id,predecessor_task_id,successor_category_id,successor_task_id)
   values(new.project_id,new.predecessor_category_id,new.predecessor_task_id,
     case when tg_table_name='estimate_categories' then new.id end,case when tg_table_name='estimate_tasks' then new.id end) on conflict do nothing;
 end if;return new;
end $$;
create trigger category_predecessor_bridge after insert or update of predecessor_category_id,predecessor_task_id on public.estimate_categories for each row execute function public.bridge_estimate_predecessor();
create trigger task_predecessor_bridge after insert or update of predecessor_category_id,predecessor_task_id on public.estimate_tasks for each row execute function public.bridge_estimate_predecessor();
create or replace function public.project_dependency_projection(p_project_id bigint)
returns void language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_sync text:=current_setting('idrmm.dependency_sync',true);
begin
 perform set_config('idrmm.dependency_sync','edges',true);
 update public.estimate_categories c set predecessor_category_id=x.predecessor_category_id,predecessor_task_id=x.predecessor_task_id
 from(select c2.id,d.predecessor_category_id,d.predecessor_task_id from public.estimate_categories c2 left join lateral(
   select predecessor_category_id,predecessor_task_id from public.estimate_dependencies where project_id=p_project_id and successor_category_id=c2.id order by predecessor_key limit 1
 )d on true where c2.project_id=p_project_id)x where c.id=x.id and (c.predecessor_category_id,c.predecessor_task_id) is distinct from (x.predecessor_category_id,x.predecessor_task_id);
 update public.estimate_tasks t set predecessor_category_id=x.predecessor_category_id,predecessor_task_id=x.predecessor_task_id
 from(select t2.id,d.predecessor_category_id,d.predecessor_task_id from public.estimate_tasks t2 left join lateral(
   select predecessor_category_id,predecessor_task_id from public.estimate_dependencies where project_id=p_project_id and successor_task_id=t2.id order by predecessor_key limit 1
 )d on true where t2.project_id=p_project_id)x where t.id=x.id and (t.predecessor_category_id,t.predecessor_task_id) is distinct from (x.predecessor_category_id,x.predecessor_task_id);
 perform set_config('idrmm.dependency_sync',coalesce(v_sync,''),true);
end $$;

create or replace function public.save_estimate_dependencies(
 p_project_id bigint,p_source_kind text,p_source_id bigint,p_predecessors text[],p_successors text[],
 p_previous_predecessors text[] default null,p_previous_successors text[] default null,p_milestone boolean default null,p_name text default null
) returns void language plpgsql security invoker set search_path=public,pg_temp as $$
declare
 v_source text;v_key text;v_in text[];v_out text[];v_current_in text[];v_current_out text[];
 v_sync text:=current_setting('idrmm.dependency_sync',true);v_count integer;
begin
 if public.app_session_is_active() is not true or public.invitation_setup_complete() is not true or public.project_access_level(p_project_id) is distinct from 'edit' then
   raise exception 'Project editing is not permitted.' using errcode='42501';end if;
 if public.system_backup_maintenance() then raise exception 'Saving is temporarily paused.' using errcode='55000';end if;
 if p_source_kind is null or p_source_kind not in ('task','category') or p_source_id is null or p_source_id<=0 or p_predecessors is null or p_successors is null
   or cardinality(p_predecessors)>2000 or cardinality(p_successors)>2000 then raise exception 'Choose valid task dependencies.' using errcode='22023';end if;
 perform pg_advisory_xact_lock(hashtextextended('idrmm-gantt-project:'||p_project_id::text,0));
 perform 1 from public.estimate_categories where project_id=p_project_id order by id for update;
 perform 1 from public.estimate_tasks where project_id=p_project_id order by id for update;
 v_source:=p_source_kind||':'||p_source_id;
 select coalesce(array_agg(distinct x order by x),'{}'::text[]) into v_in from unnest(p_predecessors)x;
 select coalesce(array_agg(distinct x order by x),'{}'::text[]) into v_out from unnest(p_successors)x;
 for v_key in select unnest(v_in||v_out||array[v_source]) loop
   if v_key is null or v_key !~ '^(task|category):[1-9][0-9]*$' then raise exception 'Choose valid task dependencies.' using errcode='22023';end if;
   if split_part(v_key,':',1)='task' then perform 1 from public.estimate_tasks where id=split_part(v_key,':',2)::bigint and project_id=p_project_id;
   else perform 1 from public.estimate_categories where id=split_part(v_key,':',2)::bigint and project_id=p_project_id;end if;
   if not found then raise exception 'Dependencies must belong to the same project.' using errcode='22023';end if;
 end loop;
 if v_source=any(v_in||v_out) then raise exception 'A task cannot depend on itself.' using errcode='22023';end if;
 if exists(select 1 from public.estimate_categories c where ('category:'||c.id)=any(v_out) and exists(select 1 from public.estimate_tasks t where t.category_id=c.id)) then
   raise exception 'Choose standalone tasks, subtasks or milestones as successors, not grouped main tasks.' using errcode='22023';end if;
 select coalesce(array_agg(predecessor_key order by predecessor_key),'{}'::text[]) into v_current_in from public.estimate_dependencies where project_id=p_project_id and successor_key=v_source;
 select coalesce(array_agg(successor_key order by successor_key),'{}'::text[]) into v_current_out from public.estimate_dependencies d where project_id=p_project_id and predecessor_key=v_source
   and not exists(select 1 from public.estimate_tasks t where t.category_id=d.successor_category_id);
 if p_previous_predecessors is not null and v_current_in is distinct from array(select distinct x from unnest(p_previous_predecessors)x order by x)
   or p_previous_successors is not null and v_current_out is distinct from array(select distinct x from unnest(p_previous_successors)x order by x) then
   raise exception 'Dependencies changed while this form was open. Reopen the task and retry.' using errcode='40001';end if;
 if p_source_kind='category' and p_milestone is true and exists(select 1 from public.estimate_tasks where category_id=p_source_id) then
   raise exception 'A main task with subtasks cannot be a milestone.' using errcode='22023';end if;
 perform set_config('idrmm.dependency_sync','edges',true);
 if p_source_kind='category' then
   if p_name is not null and nullif(trim(p_name),'') is null then raise exception 'Task name is required.' using errcode='22023';end if;
   update public.estimate_categories set category_name=coalesce(trim(p_name),category_name),is_milestone=coalesce(p_milestone,is_milestone) where id=p_source_id and project_id=p_project_id;
 else update public.estimate_tasks set is_milestone=coalesce(p_milestone,is_milestone) where id=p_source_id and project_id=p_project_id;end if;
 get diagnostics v_count=row_count;if v_count<>1 then raise exception 'Task editing was denied.' using errcode='42501';end if;
 delete from public.estimate_dependencies where project_id=p_project_id and successor_key=v_source and not(predecessor_key=any(v_in));
 delete from public.estimate_dependencies d where project_id=p_project_id and predecessor_key=v_source and not(successor_key=any(v_out)) and not exists(select 1 from public.estimate_tasks t where t.category_id=d.successor_category_id);
 insert into public.estimate_dependencies(project_id,predecessor_category_id,predecessor_task_id,successor_category_id,successor_task_id)
 select p_project_id,case when split_part(a,':',1)='category' then split_part(a,':',2)::bigint end,case when split_part(a,':',1)='task' then split_part(a,':',2)::bigint end,
   case when split_part(b,':',1)='category' then split_part(b,':',2)::bigint end,case when split_part(b,':',1)='task' then split_part(b,':',2)::bigint end
 from(select unnest(v_in) a,v_source b union select v_source a,unnest(v_out) b)x on conflict do nothing;
 perform public.assert_estimate_dependency_graph(p_project_id);perform public.project_dependency_projection(p_project_id);
 perform set_config('idrmm.dependency_sync',coalesce(v_sync,''),true);
end $$;

