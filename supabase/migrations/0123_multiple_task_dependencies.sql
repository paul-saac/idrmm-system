-- Preserve old Undo/Redo: reconstruct each snapshot's own links. Match current
-- links' identity/metadata when possible; reserve unique IDs for historical links.
update public.gantt_snapshots s set snapshot=jsonb_set(s.snapshot,'{dependencies}',coalesce((
 select jsonb_agg(y.edge order by (y.edge->>'id')::bigint) from(
 select coalesce((select to_jsonb(d) from public.estimate_dependencies d where d.project_id=s.project_id
   and d.predecessor_key=x.predecessor and d.successor_key=x.successor),
   jsonb_build_object('id',nextval('public.estimate_dependencies_id_seq'),'project_id',s.project_id,
   'predecessor_category_id',x.row->'predecessor_category_id','predecessor_task_id',x.row->'predecessor_task_id',
   'successor_category_id',case when x.kind='category' then (x.row->>'id')::bigint end,'successor_task_id',case when x.kind='task' then (x.row->>'id')::bigint end,
   'predecessor_key',x.predecessor,'successor_key',x.successor,'created_at',s.created_at,'created_by',s.created_by)) edge
 from(select a.row,a.kind,coalesce('category:'||(a.row->>'predecessor_category_id'),'task:'||(a.row->>'predecessor_task_id')) predecessor,
   a.kind||':'||(a.row->>'id') successor from(
   select value row,'category' kind from jsonb_array_elements(coalesce(s.snapshot->'categories','[]'::jsonb))
   union all select value row,'task' kind from jsonb_array_elements(coalesce(s.snapshot->'tasks','[]'::jsonb)))a
 where coalesce(a.row->>'predecessor_category_id',a.row->>'predecessor_task_id') is not null)x)y
),'[]'::jsonb)) where not(s.snapshot?'dependencies');

